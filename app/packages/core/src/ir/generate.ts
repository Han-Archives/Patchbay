import type { Ir, IrCap, IrEdge, IrEval, IrNode, IrStateField, IrTool } from "../types/ir.js";
import { RESERVED_NODE_IDS } from "../types/ir.js";

/**
 * 2.1–2.3: turn an approved IR into a one-shot LangGraph scaffold
 * (기획서 원칙 3). Pure: this module returns strings and a node-set
 * comparison. Writing to disk is `studio/generateScaffold.ts`, because a
 * generator that also wrote would make the "never overwrite" rule a
 * local convention instead of the only write path.
 *
 * The kernel does not call a model. `type` strings are copied as-is
 * (명세 §3 State). Caps and human-approval sites become comments and
 * stubs (명세 §4.3 ②) — Patchbay does not enforce them at runtime.
 */

export const SCAFFOLD_FILES = {
  state: "state.ts",
  graph: "graph.ts",
  evals: "evals.test.ts",
} as const;

export const DEFAULT_SCAFFOLD_DIR = "src/agent";

export interface ScaffoldSources {
  [SCAFFOLD_FILES.state]: string;
  [SCAFFOLD_FILES.graph]: string;
  [SCAFFOLD_FILES.evals]: string;
}

export interface NodeSetComparison {
  ir: string[];
  graph: string[];
  missing: string[];
  extra: string[];
  match: boolean;
}

const START = "__start__";
const END = "__end__";

function header(ir: Ir, extra: string): string {
  return (
    `/**\n` +
    ` * Generated by \`patchbay ir generate\` from IR v${ir.version} (${ir.graph || ir.project}).\n` +
    ` * One-shot scaffold — Patchbay will not overwrite this file (원칙 3).\n` +
    (extra ? ` * ${extra}\n` : "") +
    (ir.environment
      ? ` * 실행 환경: ${[ir.environment.language, ir.environment.runtime, ir.environment.location === "remote" ? `원격 ${ir.environment.remote?.host ?? ""} (터널 ${ir.environment.remote?.tunnel ?? ""})` : "로컬"].filter(Boolean).join(" · ")}\n`
      : "") +
    ` */\n`
  );
}

/** `my-node` is a valid LangGraph id but not a valid function name. */
export function jsIdent(id: string, fallbackPrefix: string): string {
  const cleaned = id.replace(/[^A-Za-z0-9_]/g, "_");
  const body = /^[A-Za-z_]/.test(cleaned) ? cleaned : `${fallbackPrefix}_${cleaned}`;
  return body;
}

function pascal(id: string): string {
  const ident = jsIdent(id, "Node");
  return ident.charAt(0).toUpperCase() + ident.slice(1);
}

function needsBaseMessage(ir: Ir): boolean {
  return ir.state.some((field) => field.type.includes("BaseMessage"));
}

/**
 * IR의 타입 글을 TypeScript 타입으로 (2026-10-07, 실제 설계에서 `array` · `object` 가 그대로 옮겨져 컴파일이 깨졌다).
 * 정확한 타입(`string[]` · `BaseMessage[]`)은 그대로 두고, 느슨한 낱말만 바꾼다. 처음 값이 `null` 이면 타입에 null 을 더한다.
 */
const LOOSE_TYPES: Record<string, string> = {
  array: "unknown[]", list: "unknown[]", 배열: "unknown[]", 목록: "unknown[]",
  object: "Record<string, unknown>", record: "Record<string, unknown>", map: "Record<string, unknown>", dict: "Record<string, unknown>", 객체: "Record<string, unknown>",
  text: "string", str: "string", 문자열: "string", 글: "string", date: "string", datetime: "string",
  int: "number", integer: "number", float: "number", 숫자: "number", num: "number",
  bool: "boolean", 불: "boolean", any: "unknown",
};

export function tsType(field: Pick<IrStateField, "type" | "default">): string {
  const raw = field.type.trim();
  const base = LOOSE_TYPES[raw.toLowerCase()] ?? LOOSE_TYPES[raw] ?? raw;
  const nullable = field.default.trim() === "null" && !/\bnull\b/.test(base);
  return nullable ? `${/[|&]/.test(base) ? `(${base})` : base} | null` : base;
}

function reducerExpr(field: IrStateField): string {
  if (field.reducer === "append") return "(left, right) => left.concat(right)";
  if (field.reducer === "lastWrite") return "(_left, right) => right";
  const ref = field.reducerRef ? ` — ${field.reducerRef}` : "";
  return (
    `(left, right) => {\n` +
    `      void left; void right;\n` +
    `      throw new Error(${JSON.stringify(`${field.field}: custom reducer는 2.4가 채운다${ref}`)});\n` +
    `    }`
  );
}

export function generateStateTs(ir: Ir): string {
  const imports = [
    `import { Annotation } from "@langchain/langgraph";`,
    ...(needsBaseMessage(ir) ? [`import type { BaseMessage } from "@langchain/core/messages";`] : []),
  ];
  const fields = ir.state.map((field) => {
    return (
      `  ${field.field}: Annotation<${tsType(field)}>({\n` +
      `    reducer: ${reducerExpr(field)},\n` +
      `    default: () => (${field.default}),\n` +
      `  }),`
    );
  });
  return (
    header(ir, "2.1 State — the netlist, compiled.") +
    `\n` +
    imports.join("\n") +
    `\n\n` +
    `export const State = Annotation.Root({\n` +
    fields.join("\n") +
    `\n});\n\n` +
    `export type State = typeof State.State;\n`
  );
}

function capLines(ir: Ir, node: IrNode): { comment: string[]; needsGate: string[] } {
  const tools = node.tools
    .map((id) => ir.tools.find((tool) => tool.id === id))
    .filter((tool): tool is IrTool => Boolean(tool));
  const models = node.models
    .map((id) => ir.models.find((model) => model.id === id))
    .filter((model): model is Ir["models"][number] => Boolean(model));
  const capIds = new Set<string>();
  for (const tool of tools) for (const cap of tool.caps) capIds.add(cap);
  for (const model of models) for (const cap of model.caps) capIds.add(cap);

  const comment: string[] = [];
  if (capIds.size > 0) {
    const bits = [...capIds].map((id) => {
      const owners = [
        ...tools.filter((tool) => tool.caps.includes(id as IrTool["caps"][number])).map((tool) => tool.id),
        ...models.filter((model) => model.caps.includes(id as Ir["models"][number]["caps"][number])).map((model) => model.id),
      ];
      return owners.length ? `${id} (${owners.join(", ")})` : id;
    });
    comment.push(` * 권한: ${bits.join(" · ")}`);
  } else {
    comment.push(` * 권한: 없음`);
  }

  const gates: string[] = [];
  for (const tool of tools) {
    if (tool.irreversible) gates.push(tool.id);
  }
  for (const capId of capIds) {
    const cap = ir.caps.find((entry: IrCap) => entry.id === capId);
    if (cap?.humanApproval && !gates.includes(cap.id)) gates.push(cap.id);
  }
  if (gates.length) {
    comment.push(` * 사람 확인: ${gates.join(" · ")} — 이 호출 앞에 사람 확인이 있어야 한다`);
  } else {
    comment.push(` * 사람 확인: 없음`);
  }
  return { comment, needsGate: gates };
}

function outgoing(ir: Ir, from: string): IrEdge[] {
  return ir.edges.filter((edge) => edge.from === from);
}

function destExpr(to: string): string {
  if (to === START) return "START";
  if (to === END) return "END";
  return JSON.stringify(to);
}

function generateNodeFn(ir: Ir, node: IrNode): string {
  const ident = jsIdent(node.id, "node");
  const { comment, needsGate } = capLines(ir, node);
  const reads = node.reads.length ? node.reads.join(", ") : "없음";
  const writes = node.writes.length ? node.writes.join(", ") : "없음";
  const gateStubs = needsGate.map((action) => `  await humanGate(${JSON.stringify(action)});`).join("\n");
  return (
    `/**\n` +
    ` * ${node.id} — ${node.label}\n` +
    ` * reads: ${reads} · writes: ${writes}\n` +
    comment.join("\n") +
    `\n */\n` +
    `async function ${ident}(_state: State): Promise<Partial<State>> {\n` +
    (gateStubs ? `${gateStubs}\n` : "") +
    `  throw new Error(${JSON.stringify(`${node.id}: 노드 내부는 아직 비어 있다 (2.4)`)});\n` +
    `}\n`
  );
}

function generateRouter(from: string, edges: IrEdge[]): string {
  const ident = `routeFrom${pascal(from)}`;
  const whens = edges
    .map((edge) => `  // → ${edge.to}${edge.when ? ` when: ${edge.when}` : " (기본)"}`)
    .join("\n");
  const union = edges.map((edge) => JSON.stringify(edge.to)).join(" | ");
  return (
    `function ${ident}(_state: State): ${union} {\n` +
    `${whens}\n` +
    `  throw new Error(${JSON.stringify(`${from}: 분기 조건은 아직 비어 있다 (2.4)`)});\n` +
    `}\n`
  );
}

function generateHumanGate(): string {
  return (
    `/** 런타임 강제는 이 그래프의 몫이다 (명세 §4.3). Patchbay는 주석과 이 스텁만 넣는다. */\n` +
    `async function humanGate(action: string): Promise<void> {\n` +
    `  throw new Error(\`사람 확인이 필요하다: \${action}\`);\n` +
    `}\n`
  );
}

export function generateGraphTs(ir: Ir): string {
  const anyGate = ir.nodes.some((node) => capLines(ir, node).needsGate.length > 0);
  const routers: string[] = [];
  const wiring: string[] = [];

  const froms = [...new Set(ir.edges.map((edge) => edge.from))];
  for (const from of froms) {
    const edges = outgoing(ir, from);
    const fromExpr = destExpr(from);
    if (edges.length === 1 && !edges[0]!.when) {
      wiring.push(`  .addEdge(${fromExpr}, ${destExpr(edges[0]!.to)})`);
      continue;
    }
    if (from === START) {
      for (const edge of edges) {
        wiring.push(`  .addEdge(START, ${destExpr(edge.to)})`);
      }
      continue;
    }
    routers.push(generateRouter(from, edges));
    const paths = edges
      .map((edge) => `    ${JSON.stringify(edge.to)}: ${destExpr(edge.to)},`)
      .join("\n");
    wiring.push(
      `  .addConditionalEdges(${fromExpr}, routeFrom${pascal(from)}, {\n${paths}\n  })`,
    );
  }

  const nodeFns = ir.nodes.map((node) => generateNodeFn(ir, node));
  const addNodes = ir.nodes
    .map((node) => `  .addNode(${JSON.stringify(node.id)}, ${jsIdent(node.id, "node")})`)
    .join("\n");

  return (
    header(ir, "2.2 Node shells and edges. Ownership of this file moves to the code after this write.") +
    `\n` +
    `import { END, START, StateGraph } from "@langchain/langgraph";\n` +
    `import { State } from "./state.js";\n\n` +
    (anyGate ? generateHumanGate() + "\n" : "") +
    nodeFns.join("\n") +
    (routers.length ? "\n" + routers.join("\n") : "") +
    `\n` +
    `export const graph = new StateGraph(State)\n` +
    addNodes +
    `\n` +
    wiring.join("\n") +
    `\n` +
    `  .compile();\n`
  );
}

function initialStateLiteral(ir: Ir): string {
  const lines = ir.state.map((field) => `    ${field.field}: ${field.default},`);
  return `{\n${lines.join("\n")}\n  }`;
}

/**
 * 시험 입력을 어느 State 칸에 넣나. 「input」 칸이 늘 있다고 가정했다가 실제 설계에서 깨졌다 (2026-10-07).
 * 순서: 받는 개념(kind input)을 가리키는 칸 → 이름이 input 인 칸 → 첫 단계가 읽는 첫 칸. 없으면 null — 입력은 주석으로만.
 */
export function evalInputField(ir: Ir): IrStateField | null {
  const inputConcepts = new Set(ir.concepts.filter((c) => c.kind === "input").map((c) => c.id));
  const byConcept = ir.state.find((f) => f.concept && inputConcepts.has(f.concept));
  if (byConcept) return byConcept;
  const named = ir.state.find((f) => f.field === "input");
  if (named) return named;
  const entry = ir.edges.find((e) => e.from === START)?.to;
  const firstRead = ir.nodes.find((n) => n.id === entry)?.reads[0];
  return ir.state.find((f) => f.field === firstRead) ?? null;
}

function evalInputLine(field: IrStateField | null, input: string): string {
  if (!field) return `      // 입력: ${JSON.stringify(input)} — 넣을 State 칸이 설계에 없다. 2.4가 정한다.\n`;
  const type = tsType(field);
  if (type === "string") return `      ${field.field}: ${JSON.stringify(input)},\n`;
  // 문자열이 아닌 칸이면 원문을 그대로 두고 2.4가 모양을 맞춘다 — 타입 검사는 통과하게.
  return `      ${field.field}: ${JSON.stringify(input)} as unknown as State[${JSON.stringify(field.field)}],\n`;
}

function generateEvalTest(evaluation: IrEval, inputField: IrStateField | null = null): string {
  const title = `${evaluation.id} · ${evaluation.node} · ${evaluation.kind}`;
  if (evaluation.kind === "model") {
    return (
      `  it(${JSON.stringify(title)}, () => {\n` +
      `    // 고정 응답 어댑터로만 재현한다 (명세 §8). CI는 실제 모델 API를 부르지 않는다.\n` +
      `    throw new Error(${JSON.stringify(`${evaluation.id}: 기대 = ${evaluation.expect}`)});\n` +
      `  });`
    );
  }
  return (
    `  it(${JSON.stringify(title)}, async () => {\n` +
    `    const result = await graph.invoke({\n` +
    `      ...initialState,\n` +
    evalInputLine(inputField, evaluation.input) +
    `    });\n` +
    `    void result;\n` +
    `    throw new Error(${JSON.stringify(`${evaluation.id}: 기대 = ${evaluation.expect}`)});\n` +
    `  });`
  );
}

export function generateEvalsTestTs(ir: Ir): string {
  const inputField = evalInputField(ir);
  const tests = ir.evals.map((evaluation) => generateEvalTest(evaluation, inputField)).join("\n\n");
  return (
    header(
      ir,
      "2.3 Failing tests from evals[]. They must fail until 2.4 fills the node bodies.\n * 필요: vitest — 프로젝트에 없으면 `npm i -D vitest` (또는 yarn add -D vitest).",
    ) +
    `\n` +
    `import { describe, it } from "vitest";\n` +
    `import { graph } from "./graph.js";\n` +
    `import type { State } from "./state.js";\n\n` +
    `const initialState: State = ${initialStateLiteral(ir)};\n\n` +
    `describe(${JSON.stringify(`evals from IR v${ir.version}`)}, () => {\n` +
    tests +
    `\n});\n`
  );
}

export function generateScaffoldSources(ir: Ir): ScaffoldSources {
  return {
    [SCAFFOLD_FILES.state]: generateStateTs(ir),
    [SCAFFOLD_FILES.graph]: generateGraphTs(ir),
    [SCAFFOLD_FILES.evals]: generateEvalsTestTs(ir),
  };
}

/** Pull node ids out of a (possibly hand-edited) graph.ts. Ignores START/END. */
export function extractGraphNodeIds(source: string): string[] {
  const ids: string[] = [];
  const pattern = /\.addNode\(\s*["'`]([^"'`]+)["'`]/g;
  let match: RegExpExecArray | null;
  while ((match = pattern.exec(source))) {
    const id = match[1]!;
    if ((RESERVED_NODE_IDS as readonly string[]).includes(id)) continue;
    if (!ids.includes(id)) ids.push(id);
  }
  return ids;
}

export function compareNodeSets(ir: Ir, graphSource: string): NodeSetComparison {
  const irIds = ir.nodes.map((node) => node.id);
  const graph = extractGraphNodeIds(graphSource);
  const missing = irIds.filter((id) => !graph.includes(id));
  const extra = graph.filter((id) => !irIds.includes(id));
  return { ir: irIds, graph, missing, extra, match: missing.length === 0 && extra.length === 0 };
}
