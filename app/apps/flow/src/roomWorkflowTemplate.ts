/** 프로젝트의 기존 LangGraph 런타임에 등록할 그래프. 상태 전이와 재개는 LangGraph가 맡는다. */
export const ROOM_WORKFLOW_SOURCE = String.raw`// Generated by Patchbay. Consultation owns Plan; this graph executes an adopted design.
import { Annotation, StateGraph, START, END, interrupt } from "@langchain/langgraph";

const State = Annotation.Root({
  execution: Annotation<any>(),
  phase: Annotation<string>(),
  allocation: Annotation<any>(),
  cursor: Annotation<number>(),
  attempt: Annotation<number>(),
  outputs: Annotation<any[]>(),
  verification: Annotation<any>(),
  error: Annotation<string>(),
});
function request(s: typeof State.State, kind: string, stage: string, extra: object = {}) {
  return { protocol: 1, kind, stage, executionId: s.execution.id,
    operationId: [s.execution.id, stage, s.cursor ?? 0, s.attempt ?? 1].join(":"), ...extra };
}
function answer(value: any, s: typeof State.State) {
  if (!value || value.executionId !== s.execution.id) throw new Error("Wrong execution response");
  return value;
}
const builder = new StateGraph(State)
  .addNode("prepare", (s) => {
    const r = answer(interrupt(request(s, "model", "prepare", { memberId: s.execution.leaderId })), s);
    return r.ok ? { allocation: r.result, phase: "approval", cursor: 0, attempt: 1, outputs: [] }
      : { phase: "failed", error: r.error ?? "Allocation failed" };
  })
  .addNode("approval", (s) => {
    const r = answer(interrupt(request(s, "approval", "prepare", { allocation: s.allocation })), s);
    if (r.action === "consult") return { phase: "consult" };
    if (r.action !== "approve") throw new Error("Execution approval required");
    return { allocation: r.allocation ?? s.allocation, phase: "act" };
  })
  .addNode("act", (s) => {
    const task = s.allocation.assignments[s.cursor];
    const r = answer(interrupt(request(s, "model", "act", { memberId: task.memberId, task })), s);
    return r.ok ? { outputs: [...s.outputs, { taskId: task.id, attempt: s.attempt, text: r.result }], phase: "check" }
      : { phase: "failed", error: r.error ?? "Act failed" };
  })
  .addNode("check", (s) => {
    const task = s.allocation.assignments[s.cursor];
    const r = answer(interrupt(request(s, "model", "check", { memberId: s.execution.reviewerId, task })), s);
    if (!r.ok) return { phase: "failed", error: r.error ?? "Check failed" };
    const v = r.result;
    if (v.outcome === "consult") return { verification: v, phase: "consult" };
    if (v.outcome !== "passed" || !v.tests?.passed) return { verification: v, phase: "check_failed" };
    const next = s.cursor + 1;
    return { verification: v, cursor: next, attempt: 1,
      phase: next < s.allocation.assignments.length ? "act" : "deploy_approval" };
  })
  .addNode("check_failed", (s) => {
    const r = answer(interrupt(request(s, "check_failed", "check", { verification: s.verification })), s);
    if (r.action === "consult") return { phase: "consult" };
    if (r.action !== "retry" || s.attempt >= s.execution.maxAttempts) return { phase: "failed", error: "Retry limit reached" };
    return { phase: "act", attempt: s.attempt + 1 };
  })
  .addNode("deploy_approval", (s) => {
    const r = answer(interrupt(request(s, "deploy_approval", "deploy", { target: s.execution.deployTarget, verification: s.verification })), s);
    if (r.action === "consult") return { phase: "consult" };
    if (r.action === "finish" && !s.execution.deployCommand) return { phase: "done" };
    if (r.action !== "deploy" || r.target !== s.execution.deployTarget || !s.execution.deployCommand) throw new Error("Deployment target approval required");
    return { phase: "deploy" };
  })
  .addNode("deploy", (s) => {
    const r = answer(interrupt(request(s, "command", "deploy")), s);
    return r.ok && r.result?.passed ? { phase: "done" } : { phase: "failed", error: r.error ?? "Deployment failed" };
  })
  .addEdge(START, "prepare")
  .addConditionalEdges("prepare", s => s.phase === "approval" ? "approval" : END)
  .addConditionalEdges("approval", s => s.phase === "consult" ? END : "act")
  .addConditionalEdges("act", s => s.phase === "check" ? "check" : END)
  .addConditionalEdges("check", s => ["act", "check_failed", "deploy_approval"].includes(s.phase) ? s.phase : END)
  .addConditionalEdges("check_failed", s => s.phase === "act" ? "act" : END)
  .addConditionalEdges("deploy_approval", s => s.phase === "deploy" ? "deploy" : END)
  .addEdge("deploy", END);
// The LangGraph server supplies its existing checkpointer. No new database here.
export const graph = builder.compile();
`;
