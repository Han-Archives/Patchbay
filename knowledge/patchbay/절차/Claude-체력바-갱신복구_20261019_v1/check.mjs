import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
const root=process.cwd(),require=createRequire(path.join(root,'app/apps/flow/package.json'));
const {chromium}=require('/private/tmp/patchbay-kg-browser/node_modules/playwright-core');
const {serve}=require('@hono/node-server');
const core=await import(path.join(root,'app/packages/core/dist/index.js'));
const {createFlowApp}=await import(path.join(root,'app/apps/flow/dist-server/server.js'));
const {createClaudeQuotaRefresh}=await import(path.join(root,'app/apps/flow/dist-server/claudeQuotaHost.js'));
const out='/private/tmp/patchbay-claude-quota-check';await fs.mkdir(out,{recursive:true});
const browser=await chromium.launch({headless:true,executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',args:['--no-first-run','--disable-background-networking','--use-mock-keychain']});
const checks=[],errors=[];const check=(ok,name)=>{assert.ok(ok,name);checks.push(name)};
let app,server,modelCalls=0;
const newHome=async()=>{const h=await fs.mkdtemp(path.join(os.tmpdir(),'pb-quota-fixed-'));await core.ensureStudioInitialized(h);return h};
const stamp=()=>new Date();
const window=(used,hours=5)=>({used_percentage:used,resets_at:new Date(Date.now()+hours*3600000).toISOString()});
const context=await browser.newContext({viewport:{width:1512,height:1100}});
const page=await context.newPage();page.on('pageerror',e=>errors.push(e.message));
await page.route('**/api/**',route=>['GET','HEAD'].includes(route.request().method())?route.continue():route.fulfill({status:200,contentType:'application/json',body:'{}'}));
const rail=page.locator('.rail-hp-row').filter({has:page.locator('b',{hasText:'CL'})});
const card=page.locator('.hp-card').filter({hasText:'Claude Code'});
try{
 if(process.argv.includes('--live')){
  const responsePromise=page.waitForResponse(r=>new URL(r.url()).pathname==='/api/llm-quota');
  await page.goto('http://127.0.0.1:4318');
  const body=await (await responsePromise).json(),claude=body.providers.find(p=>p.provider==='claude-code');
  check(claude.rateStatus==='fresh','live native observation is fresh');
  check(claude.hpPct!==null,'live Claude percentage is available');
  await page.waitForFunction(pct=>[...document.querySelectorAll('.rail-hp-row')].find(el=>el.querySelector('b')?.textContent==='CL')?.textContent.includes(pct+'%'),claude.hpPct);
  check((await rail.innerText()).includes(claude.hpPct+'%'),'live rail matches native percentage');
  await page.getByRole('button',{name:'LLM 구독 체력 상태',exact:true}).click();
  check((await card.innerText()).includes('확인'),'live popover shows observation time');
  await page.screenshot({path:path.join(out,'live.png'),fullPage:true});
  await fs.writeFile(path.join(out,'live.json'),JSON.stringify({at:new Date().toISOString(),checks,claude,errors},null,2));
  console.log(JSON.stringify({live:true,checks:checks.length,hpPct:claude.hpPct,session:claude.session.remainingPct,weekly:claude.weekly.remainingPct,errors}));
 }else{
  const home=await newHome(),repo=path.join(home,'repo');await fs.mkdir(repo);await core.registerProject(home,{alias:'demo',kind:'local_repo',path:repo,name:'가상 체력 검증'});
  let sessionUsed=35,reads=0;
  const reader=async()=>{reads++;return {rate_limits_available:true,rate_limits:{five_hour:{utilization:sessionUsed,resets_at:window(0).resets_at},seven_day:{utilization:21,resets_at:window(0,168).resets_at}}}};
  let refresh=createClaudeQuotaRefresh(home,reader);
  app=createFlowApp({studioHome:home,claudeQuotaRefresh:()=>refresh(),roomRunner:async()=>{modelCalls++;throw Error('No model calls allowed')}});
  server=serve({fetch:app.fetch,hostname:'127.0.0.1',port:0});await new Promise(r=>server.listening?r():server.once('listening',r));
  const base='http://127.0.0.1:'+server.address().port;
  await page.goto(base);await page.waitForFunction(()=>document.querySelector('.rail-hp-row')?.textContent?.includes('65%'));
  check((await rail.innerText()).includes('65%'),'fresh native result shows 65%');
  await page.getByRole('button',{name:'LLM 구독 체력 상태',exact:true}).click();
  check((await card.innerText()).includes('확인'),'fresh observation time is visible');
  await page.screenshot({path:path.join(out,'fresh.png'),fullPage:true});
  sessionUsed=45;refresh=createClaudeQuotaRefresh(home,reader);
  await page.waitForFunction(()=>document.querySelector('.rail-hp-row')?.textContent?.includes('55%'),{timeout:20000});
  check((await rail.innerText()).includes('55%'),'15-second refresh updates 65% to 55%');
  check(reads===2,'only two injected native reads');
  const partialHome=await newHome();
  await core.recordClaudeRateLimits(partialHome,{rate_limits:{seven_day:window(8,168)}},stamp());
  let snapshot=await core.loadLlmQuotaSnapshot(partialHome,stamp(),{hostHome:null});
  await page.route('**/api/llm-quota',route=>route.fulfill({status:200,contentType:'application/json',body:JSON.stringify(snapshot)}));
  await page.reload();await page.waitForFunction(()=>document.querySelector('.rail-hp-row')?.textContent?.includes('92%'));
  check((await rail.innerText()).includes('7일 기준'),'partial quota identifies the known period');
  await page.getByRole('button',{name:'LLM 구독 체력 상태',exact:true}).click();
  check((await card.innerText()).includes('나머지 사용률은 갱신 대기'),'partial status explains missing period');
  snapshot=await core.loadLlmQuotaSnapshot(partialHome,new Date(Date.now()+6*60000),{hostHome:null});
  await page.reload();await page.waitForFunction(()=>document.querySelector('.rail-hp-row')?.textContent?.includes('갱신 대기'));
  check(!(await rail.innerText()).includes('92%'),'stale quota is not presented as current');
  await page.getByRole('button',{name:'LLM 구독 체력 상태',exact:true}).click();
  check((await card.innerText()).includes('마지막 92%'),'last known quota remains visible in details');
  check((await card.innerText()).includes('사용률 갱신 지연'),'stale status is explicit');
  await page.setViewportSize({width:390,height:1000});
  const rect=await page.locator('.hp-popover').boundingBox();
  check(rect&&rect.x>=0&&rect.x+rect.width<=391,'mobile popover stays inside viewport');
  await page.screenshot({path:path.join(out,'mobile-stale.png'),fullPage:true});
  const empty=await newHome();snapshot=await core.loadLlmQuotaSnapshot(empty,stamp(),{hostHome:null});
  await page.reload();await page.waitForFunction(()=>document.querySelector('.rail-hp-row')?.textContent?.includes('갱신 대기'));
  check(!(await rail.innerText()).includes('%'),'missing usage does not invent a percentage');
  await core.recordClaudeRateLimits(empty,{rate_limits:{five_hour:window(5),seven_day:window(1,168)}},stamp());
  snapshot=await core.loadLlmQuotaSnapshot(empty,stamp(),{hostHome:null});
  await page.reload();await page.waitForFunction(()=>document.querySelector('.rail-hp-row')?.textContent?.includes('95%'));
  check((await rail.innerText()).includes('95%'),'fresh reset window restores the new observed percentage');
  check(modelCalls===0,'model calls remain zero');check(errors.length===0,'browser errors remain zero');
  await fs.writeFile(path.join(out,'validation.json'),JSON.stringify({at:new Date().toISOString(),checks,count:checks.length,modelCalls,errors},null,2));
  console.log(JSON.stringify({checks:checks.length,modelCalls,errors}));
 }
}finally{await context.close();await browser.close();if(app)await app.close();if(server){server.closeAllConnections();await new Promise(r=>server.close(r))}}
